#!/usr/bin/env python3
"""Generate sigmoid handoff variants from catalog experiments and YAML overrides.

Python owns generation only; deployment choices remain in the input YAML.
Generated experiments stay ordinary standalone loader inputs. Never start services.
"""

import argparse
from pathlib import Path

import yaml

from manimux.cli import _merge, load_config, read_yaml


def generate(spec_path: Path, *, check: bool = False) -> list[Path]:
    spec = read_yaml(spec_path)
    catalog_path = spec_path.parent / spec["catalog"]
    catalog = read_yaml(catalog_path)
    entries = {entry["id"]: entry for entry in catalog["experiments"]}
    outputs, variants = {}, []
    for base_id in spec["experiments"]:
        base = entries[base_id]
        source_path = catalog_path.parent / base["config"]
        source = read_yaml(source_path)
        for mode, overrides in spec["modes"].items():
            suffix = "_sigmoid_smooth" + ("" if mode == "chunk" else f"_{mode}")
            label = "Chunk IK" if mode == "chunk" else "Step IK"
            config = _merge(_merge(source, spec["overrides"]), overrides)
            for key in ("output_dir", "condition"):
                config["run"][key] += suffix
            config["robogui"]["policy_label"] = (
                source["robogui"]["policy_label"].replace(" / No Blend", "")
                + f" / Sigmoid / {label}"
            )
            path = source_path.with_stem(source_path.stem + suffix)
            outputs[path] = (
                "# Generated by scripts/experiments/build_sigmoid_variants.py "
                f"from {spec_path.name}.\n"
                "# Edit the base experiment or generator YAML, then regenerate.\n"
                + yaml.safe_dump(config, sort_keys=False)
            )
            variants.append({
                **base, "id": base_id + suffix,
                "label": base["label"].replace(" / No Blend", "") + f" / Sigmoid / {label}",
                "config": path.relative_to(catalog_path.parent).as_posix(),
            })
    generated_ids = {entry["id"] for entry in variants}
    catalog["experiments"] = [
        entry for entry in catalog["experiments"] if entry["id"] not in generated_ids
    ] + variants
    outputs[catalog_path] = yaml.safe_dump(catalog, sort_keys=False)
    if check:
        stale = [str(path) for path, content in outputs.items()
                 if not path.exists() or path.read_text() != content]
        if stale:
            raise ValueError(f"Regenerate stale sigmoid variants: {', '.join(stale)}")
    else:
        for path, content in outputs.items():
            path.write_text(content)
    experiments = [path for path in outputs if path != catalog_path]
    for path in experiments:
        load_config(path)
    return experiments


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("spec", type=Path)
    parser.add_argument("--check", action="store_true", help="Check drift without rewriting files")
    args = parser.parse_args()
    paths = generate(args.spec, check=args.check)
    print(f"Validated {len(paths)} sigmoid experiments")
